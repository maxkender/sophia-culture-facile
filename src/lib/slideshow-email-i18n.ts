export const POSTER_DICTS: Partial<Record<PosterLang, PosterDict>> = { en, fr, de, es, 'pt-BR': ptBR, pt, it, nl, sv, fi, nb, da, et, lv, lt, pl, cs, sk, sl, hr, sr, bs, hu, ro, el, tr, id };

/** Language from the application's country; any missing or incomplete dictionary falls back to English. */
export function posterLangFor(country: string | null | undefined): PosterLang {
  const code = countryCodeOf(country);
  const lang = (code && BY_COUNTRY[code]) || 'en';
  const d = POSTER_DICTS[lang];
  return d && KEYS.every(k => typeof d[k] === 'string' && d[k].length > 0) ? lang : 'en';
}
export const posterDict = (lang: PosterLang): PosterDict => POSTER_DICTS[lang] ?? en;
export function fill(s: string, v: Record<string, string>) { return s.replace(/\{(\w+)\}/g, (m, k) => v[k] ?? m); }
export function formatPosterDate(date: string, lang: PosterLang) {
  return new Intl.DateTimeFormat(LOCALE[lang], { weekday: 'long', day: 'numeric', month: 'long', timeZone: 'UTC' }).format(new Date(`${date}T12:00:00Z`));
}
